const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en');
  const [theme, setTheme] = useState<'dark' | 'light'>('dark');

  useEffect(() => {
    const saved = window.localStorage.getItem('twin-treasure-language');
    if (saved === 'en' || saved === 'rw') setLanguageState(saved);
    const savedTheme = window.localStorage.getItem('twin-treasure-theme');
    if (savedTheme === 'dark' || savedTheme === 'light') setTheme(savedTheme);
  }, []);

  useEffect(() => {
    window.localStorage.setItem('twin-treasure-language', language);
    document.documentElement.lang = language === 'rw' ? 'rw' : 'en';
  }, [language]);

  useEffect(() => {
    window.localStorage.setItem('twin-treasure-theme', theme);
    document.documentElement.dataset.theme = theme;
    document.documentElement.style.colorScheme = theme;
  }, [theme]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage: setLanguageState,
    theme,
    toggleTheme: () => setTheme((current) => current === 'dark' ? 'light' : 'dark'),
    t: (text) => language === 'rw' ? translations[text] ?? text : text
  }), [language, theme]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider.');
  return context;
}

export function LanguagePicker({ className = '' }: { className?: string }) {
  const { language, setLanguage, t } = useLanguage();

  return (
    <label className={`language-picker ${className}`.trim()}>
      <span>{t('Language')}</span>
      <select aria-label={t('Language')} value={language} onChange={(event) => setLanguage(event.target.value as Language)}>
        <option value="en">English</option>
        <option value="rw">Ikinyarwanda</option>
      </select>
    </label>
  );
}
