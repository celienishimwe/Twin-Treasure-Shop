CREATE TABLE IF NOT EXISTS public.users (
  id SERIAL PRIMARY KEY,
  email VARCHAR(320) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.business_capitals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_type TEXT NOT NULL CHECK (entry_type IN ('initial_contribution', 'additional_contribution', 'owner_withdrawal', 'cash_adjustment')),
  amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  description TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (length(trim(name)) > 0),
  sku TEXT,
  selling_price NUMERIC(14, 2) NOT NULL CHECK (selling_price >= 0),
  quantity_on_hand BIGINT NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
  average_cost NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (average_cost >= 0),
  reorder_level BIGINT NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.suppliers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (length(trim(name)) > 0),
  phone TEXT,
  email TEXT,
  address TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.product_purchases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id BIGINT NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
  purchase_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'received', 'cancelled')),
  reference TEXT,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.purchase_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_id BIGINT NOT NULL REFERENCES public.product_purchases(id) ON DELETE RESTRICT,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  quantity BIGINT NOT NULL CHECK (quantity > 0),
  unit_cost NUMERIC(14, 2) NOT NULL CHECK (unit_cost >= 0),
  additional_cost NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (additional_cost >= 0),
  line_total NUMERIC(14, 2) GENERATED ALWAYS AS (quantity * unit_cost + additional_cost) STORED
);

CREATE TABLE IF NOT EXISTS public.sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status TEXT NOT NULL DEFAULT 'completed' CHECK (status IN ('completed', 'void')),
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.sale_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id BIGINT NOT NULL REFERENCES public.sales(id) ON DELETE RESTRICT,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  quantity BIGINT NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(14, 2) NOT NULL CHECK (unit_price >= 0),
  unit_cost_at_sale NUMERIC(14, 2) NOT NULL CHECK (unit_cost_at_sale >= 0),
  line_total NUMERIC(14, 2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
  cost_total NUMERIC(14, 2) GENERATED ALWAYS AS (quantity * unit_cost_at_sale) STORED
);

CREATE TABLE IF NOT EXISTS public.expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category TEXT NOT NULL CHECK (length(trim(category)) > 0),
  amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
  expense_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  description TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.supplier_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id BIGINT NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
  purchase_id BIGINT REFERENCES public.product_purchases(id) ON DELETE RESTRICT,
  amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
  payment_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  method TEXT,
  reference TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.supplier_returns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id BIGINT NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
  purchase_id BIGINT REFERENCES public.product_purchases(id) ON DELETE RESTRICT,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  quantity BIGINT NOT NULL CHECK (quantity > 0),
  unit_cost NUMERIC(14, 2) NOT NULL CHECK (unit_cost >= 0),
  settlement_type TEXT NOT NULL CHECK (settlement_type IN ('supplier_credit', 'cash_refund')),
  amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
  return_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type TEXT NOT NULL CHECK (event_type IN (
    'capital_contribution',
    'owner_withdrawal',
    'cash_adjustment',
    'inventory_purchase',
    'sale',
    'operating_expense',
    'supplier_payment',
    'supplier_return'
  )),
  amount NUMERIC(14, 2) NOT NULL CHECK (amount >= 0),
  cash_impact NUMERIC(14, 2) NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  description TEXT NOT NULL,
  business_capital_id BIGINT UNIQUE REFERENCES public.business_capitals(id) ON DELETE RESTRICT,
  product_purchase_id BIGINT UNIQUE REFERENCES public.product_purchases(id) ON DELETE RESTRICT,
  sale_id BIGINT UNIQUE REFERENCES public.sales(id) ON DELETE RESTRICT,
  expense_id BIGINT UNIQUE REFERENCES public.expenses(id) ON DELETE RESTRICT,
  supplier_payment_id BIGINT UNIQUE REFERENCES public.supplier_payments(id) ON DELETE RESTRICT,
  supplier_return_id BIGINT UNIQUE REFERENCES public.supplier_returns(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT transactions_single_source CHECK (
    num_nonnulls(business_capital_id, product_purchase_id, sale_id, expense_id, supplier_payment_id, supplier_return_id) = 1
  )
);

CREATE TABLE IF NOT EXISTS public.stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  movement_type TEXT NOT NULL CHECK (movement_type IN ('purchase', 'sale', 'supplier_return', 'adjustment')),
  quantity_delta BIGINT NOT NULL CHECK (quantity_delta <> 0),
  unit_cost NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
  purchase_item_id BIGINT UNIQUE REFERENCES public.purchase_items(id) ON DELETE RESTRICT,
  sale_item_id BIGINT UNIQUE REFERENCES public.sale_items(id) ON DELETE RESTRICT,
  supplier_return_id BIGINT UNIQUE REFERENCES public.supplier_returns(id) ON DELETE RESTRICT,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT stock_movements_single_source CHECK (
    num_nonnulls(purchase_item_id, sale_item_id, supplier_return_id) <= 1
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS products_sku_unique_idx
  ON public.products (sku) WHERE sku IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS suppliers_name_unique_idx
  ON public.suppliers (lower(name));
CREATE UNIQUE INDEX IF NOT EXISTS product_purchases_supplier_reference_unique_idx
  ON public.product_purchases (supplier_id, reference) WHERE reference IS NOT NULL;
CREATE INDEX IF NOT EXISTS product_purchases_date_idx ON public.product_purchases (purchase_date);
CREATE INDEX IF NOT EXISTS product_purchases_supplier_idx ON public.product_purchases (supplier_id);
CREATE INDEX IF NOT EXISTS purchase_items_purchase_idx ON public.purchase_items (purchase_id);
CREATE INDEX IF NOT EXISTS purchase_items_product_idx ON public.purchase_items (product_id);
CREATE INDEX IF NOT EXISTS sales_date_idx ON public.sales (sale_date);
CREATE INDEX IF NOT EXISTS sale_items_sale_idx ON public.sale_items (sale_id);
CREATE INDEX IF NOT EXISTS sale_items_product_idx ON public.sale_items (product_id);
CREATE INDEX IF NOT EXISTS expenses_date_idx ON public.expenses (expense_date);
CREATE INDEX IF NOT EXISTS expenses_category_idx ON public.expenses (category);
CREATE INDEX IF NOT EXISTS supplier_payments_supplier_date_idx ON public.supplier_payments (supplier_id, payment_date);
CREATE INDEX IF NOT EXISTS supplier_payments_purchase_idx ON public.supplier_payments (purchase_id);
CREATE INDEX IF NOT EXISTS supplier_returns_supplier_date_idx ON public.supplier_returns (supplier_id, return_date);
CREATE INDEX IF NOT EXISTS supplier_returns_purchase_idx ON public.supplier_returns (purchase_id);
CREATE INDEX IF NOT EXISTS supplier_returns_product_idx ON public.supplier_returns (product_id);
CREATE INDEX IF NOT EXISTS transactions_occurred_at_idx ON public.transactions (occurred_at);
CREATE INDEX IF NOT EXISTS transactions_event_type_idx ON public.transactions (event_type);
CREATE INDEX IF NOT EXISTS stock_movements_product_date_idx ON public.stock_movements (product_id, occurred_at);
